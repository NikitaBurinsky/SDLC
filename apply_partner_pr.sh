#!/usr/bin/env bash
# ==============================================================================
# Скрипт автоматической подготовки Pull Request для напарника (роль Заказчика)
# Проект: NutriTrack (Дисциплина ЖЦРПО, Лабораторная работа №3)
# ==============================================================================

set -e

echo "=========================================================="
echo " [NutriTrack] Автоматическая подготовка PR от Заказчика   "
echo "=========================================================="

# 1. Проверка git
if ! command -v git &> /dev/null; then
    echo "[-] Ошибка: Git не установлен или не найден!"
    exit 1
fi

# 2. Проверка git репозитория
if ! git rev-parse --is-inside-work-tree &> /dev/null; then
    echo "[-] Ошибка: Запустите этот скрипт из корневой папки git-репозитория проекта!"
    exit 1
fi

# 3. Базовая ветка (lab3 или main)
BASE_BRANCH="main"
if git branch --all | grep -q "lab3"; then
    BASE_BRANCH="lab3"
fi

echo "[+] Переключаемся на базовую ветку: $BASE_BRANCH..."
git checkout "$BASE_BRANCH"

FEEDBACK_BRANCH="customer-feedback"
echo "[+] Создаем ветку '$FEEDBACK_BRANCH'..."
git checkout -B "$FEEDBACK_BRANCH"

mkdir -p srs

FEEDBACK_FILE="srs/customer-feedback.md"
echo "[+] Создаем файл замечаний: $FEEDBACK_FILE..."

cat << 'EOF' > "$FEEDBACK_FILE"
# Предложения и замечания Заказчика (Customer Feedback)

**Проект:** «NutriTrack» (Трекер-калькулятор питания)  
**Роль:** Заказчик (Customer / Представитель бизнес-сообщества)  
**Менеджер проекта:** Буринский Н.А. (гр. 450504)  
**Документ:** Спецификация требований к ПО (SRS v0.2)  
**Статус:** Передано на рассмотрение Менеджеру проекта в рамках Pull Request  

---

## 1. Преамбула
В рамках выполнения Лабораторной работы №3 по дисциплине «Жизненный цикл разработки ПО» Заказчик провел экспертизу первоначальной редакции Спецификации требований к ПО (SRS v0.2), моделей на языке SysML v2 и прототипов пользовательского интерфейса (GUI) веб-сервиса «NutriTrack».

Концепция системы признана актуальной и коммерчески жизнеспособной. Вместе с тем, для максимального удовлетворения потребностей целевой аудитории и повышения надежности системы сформирован перечень замечаний и предложений по доработке требований.

---

## 2. Перечень предложений и замечаний Заказчика

### Замечание №1: Требование учета суточного потребления воды (Гидробаланс)
- **Категория:** Функциональное требование
- **Приоритет:** Высокий (Must Have)
- **Суть замечания:** Для эффективного управления весом и метаболизмом одного лишь контроля калорий и макронутриентов недостаточно. Критическим фактором поддержания нормального обмена веществ является питьевой режим.
- **Предлагаемое решение:** 
  1. Включить в состав требований обязательный модуль учета потребления воды.
  2. Реализовать расчет рекомендованной индивидуальной нормы воды (из расчета 30 мл на 1 кг массы тела).
  3. Разместить на главном экране дневника питания наглядный интерактивный виджет с кнопками быстрой фиксации порций (стаканы по 250 мл) и отображением прогресса.

---

### Замечание №2: Уточнение формулы расчета сложных блюд при термообработке (уварка vs разваривание)
- **Категория:** Бизнес-логика / Алгоритмическое требование (Killer Feature)
- **Приоритет:** Критический (Must Have)
- **Суть замечания:** В описании функции расчета рецептов указано понятие «уварка». Однако в кулинарной практике действуют два диаметрально противоположных физических процесса:
  - Продукты с высоким содержанием животного белка (мясо, птица, рыба) при термообработке теряют влагу и жир, уменьшаясь в весе на 20–35% (ужарка/уварка), вследствие чего их удельная калорийность на 100 г готового продукта существенно *возрастает*.
  - Крупы, макаронные изделия и бобовые в процессе варки поглощают воду, увеличивая свою массу в 2–3 раза (разваривание), вследствие чего калорийность 100 г готового гарнира существенно *снижается*.
- **Предлагаемое решение:** Требую четко специфицировать и математически обосновать в SRS формулу расчета, которая будет инвариантна к направлению изменения массы (и при выкипании/ужарке, и при разваривании), гарантируя строгость диетического учета для любых рецептов.

---

### Замечание №3: Защита от ограничений частоты запросов к Open Food Facts API (Кэширование)
- **Категория:** Нефункциональное требование / Архитектура интеграции (QoS)
- **Приоритет:** Высокий (Should Have)
- **Суть замечания:** Публичный сервис Open Food Facts API имеет лимиты частоты запросов (rate limits). Если пользователи веб-приложения будут при каждом поиске продукта напрямую обращаться к внешнему API, возможны блокировки по HTTP 429 (Too Many Requests), а также деградация скорости поиска при медленном сетевом соединении.
- **Предлагаемое решение:** 
  1. Внедрить обязательное кэширование результатов поиска в локальной реляционной базе данных PostgreSQL.
  2. Первичный поиск осуществлять по локальной базе; к внешнему API обращаться только при отсутствии совпадений.
  3. Новые продукты, полученные из внешнего API, автоматически сохранять в локальную базу.

---

### Замечание №4: Интеллектуальное сканирование блюд по фото камерой смартфона (Mobile AI)
- **Категория:** Инновационное предложение
- **Приоритет:** Желательно (Nice to Have)
- **Суть замечания:** Необходимость постоянного взвешивания каждого продукта на кухонных весах создает барьер для пользователей.
- **Предлагаемое решение:** Реализовать модуль компьютерного зрения: пользователь делает фото тарелки камерой смартфона, а нейросеть автоматически сегментирует блюда, рассчитывает объем и вес каждого компонента с точностью до грамма и определяет итоговую калорийность без весов.

---

## 3. Ожидаемый результат
Прошу Менеджера проекта рассмотреть предложенные замечания, предоставить аргументированные заключения по каждому пункту и внести необходимые изменения в Спецификацию требований к ПО (SRS v1.0).
